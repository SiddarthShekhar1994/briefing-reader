class LoadAndMatchTests(unittest.TestCase):
    def fake(self) -> FakeDesktopBackend:
        tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.addCleanup(tmp.cleanup)
        return FakeDesktopBackend(tmp.name)

    def test_the_start_menu_minus_the_never_open_apps_and_odd_ids(self) -> None:
        fake = self.fake()
        fake.apps = START_MENU + [AppEntry("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", "Calculator"),   # twice
                                  AppEntry("Odd..Id", "Odd"), AppEntry("Blank.App", "   "),
                                  AppEntry("Bell.App", "Bell" + chr(7)), AppEntry(GUID + "\\Tools\\go.bat", "Go"),
                                  AppEntry("Contoso.Notes!App", "  Contoso   Notes ")]
        listed = apps.load(fake)
        self.assertEqual([app.name for app in listed.apps], ["Calculator", "Contoso Notes", "Microsoft Word",
                                                             "Spotify"])
        self.assertEqual(listed.left_out, 8)   # PowerShell, Terminal, Settings, Calculator again, 4 odd ones
        self.assertEqual(fake.asked("start_menu_apps"), [str(apps.MAX_LISTED)])
        self.assertNotIn("Spotify", repr(listed))

    def test_the_apps_the_owners_words_name(self) -> None:
        listed = [AppItem("Microsoft.Office.WINWORD.EXE.15", "Microsoft Word"),
                  AppItem("Microsoft.Office.EXCEL.EXE.15", "Microsoft Excel"),
                  AppItem("SpotifyAB.SpotifyMusic", "Spotify"),
                  AppItem("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", "Calculator")]
        self.assertEqual([app.name for app in apps.match("open my essay in Word", listed)], ["Microsoft Word"])
        self.assertEqual([app.name for app in apps.match("launch spotify please", listed)], ["Spotify"])
        self.assertEqual(apps.match("open my essay", listed), ())
        self.assertEqual(apps.match("open the Microsoft app", listed), ())          # "microsoft" names no one app
        many = [AppItem(f"App.N{n}", f"Notes {n}") for n in range(60)]
        self.assertEqual(len(apps.match("open notes", many)), apps.MAX_MATCHED)
        self.assertIs(apps.find(listed, "SpotifyAB.SpotifyMusic"), listed[2])
        self.assertIsNone(apps.find(listed, "spotifyab.spotifymusic"))             # the id exactly

    def test_the_never_open_list_has_this_parts_additions(self) -> None:
        self.assertEqual(guard.never_app("Windows Tools"), "system")
        self.assertEqual(guard.never_app("Administrative Tools"), "system")
        self.assertEqual(guard.never_app("Jarvis"), "jarvis")
        self.assertEqual(guard.never_app("Briefing reader"), "jarvis")


