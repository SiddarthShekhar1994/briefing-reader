"""The Start menu's apps Jarvis may open (SPEC sections 2.1, 2.4, 4.1 and 5.5: apps.py; no Qt).

``load(backend)`` reads the Start menu (backend.start_menu_apps: shell:AppsFolder's names and ids) and keeps only the
apps Jarvis may open: never one on the never-open list (guard.never_app, by its name, by its id read as words -
"Microsoft.WindowsTerminal..." is a terminal - and by its exe: terminals, script hosts, system and security tools,
installers, Claude, password managers, banking, trading and crypto apps, remote desktop and VM clients, Jarvis
himself), and never an id that is not of an AppsFolder id's shape (``app_id_problem``): an AUMID, or a known folder's
id or a drive followed by the exe's path - no "..", no network path, no address, no other type Windows runs than an
exe. ``match(words, apps)`` gives the apps the owner's words name for <apps> (at most 40, SPEC 4.1); the local route
"open <app>" takes an app whose whole name the owner typed (desktop.routes). A launch re-reads the Start menu and
finds the same id with the same name again (desktop.executor) before the backend opens it with no arguments.

Pure apart from ``load``'s one backend call; nothing is logged but counts.

Public API
==========
``MAX_LISTED``, ``MAX_MATCHED``; ``app_id_problem(app_id)``; ``exe_name(app_id)``; ``never(name, app_id)``;
``AppList(apps, left_out)``; ``load(backend, limit=)``; ``match(words, apps, cap=)``; ``find(apps, app_id)``.
"""

from __future__ import annotations

import logging
import re
import unicodedata
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from typing import Any

from . import guard
from .backend import AppEntry, DesktopBackend
from .context import MAX_APPS, AppItem

logger = logging.getLogger(__name__)

MAX_LISTED = 2000                       # Start-menu apps read at most
MAX_MATCHED = MAX_APPS                  # apps given to the planner at most (SPEC 4.1)
MAX_ID_CHARS = 512
# An AUMID: "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", "Microsoft.Office.WINWORD.EXE.15", "Chrome",
# "Microsoft.AutoGenerated.{...}".
_AUMID_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._{}+-]*(?:![A-Za-z0-9._{}+-]+)?")
# An exe under a known folder ("{6D809377-...}\Microsoft VS Code\Code.exe") or on a drive ("C:\Tools\app.exe").
_PATH_RE = re.compile(r"(?:\{[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}\}|[A-Za-z]:)"
                      r"(?:\\[^\\<>:\"/|?*]+)+")
# Words that are not an app's name when the owner's words are matched against the Start menu.
_FILLERS = frozenset({"open", "start", "launch", "the", "my", "a", "an", "app", "apps", "please", "jarvis", "in",
                      "with", "and", "for", "to", "of", "me", "up", "it", "on", "microsoft", "windows"})


def app_id_problem(app_id: Any) -> str:
    """Why ``app_id`` may not be launched as shell:AppsFolder\\<id> ("" when it may): not text, too long, a control or
    hidden character, a ".." or an empty part, not an AUMID nor a known folder's id or a drive followed by a path, or
    a type Windows runs other than an exe (a script, a shortcut, an internet shortcut ...)."""
    if not isinstance(app_id, str) or not app_id or len(app_id) > MAX_ID_CHARS or app_id != app_id.strip():
        return "shape"
    if any(unicodedata.category(char) == "Cc" or guard.hidden_char(char) for char in app_id):
        return "hidden_char"
    if ".." in app_id or "/" in app_id or "\\\\" in app_id:
        return "shape"
    if not (_AUMID_RE.fullmatch(app_id) or _PATH_RE.fullmatch(app_id)):
        return "shape"
    kind = guard.suffix(app_id)
    if "\\" in app_id:
        if kind != "exe":
            return "type"                                 # a path is an exe's, never a script's or a shortcut's
        if any(part.rstrip(". ") != part for part in app_id.split("\\")[1:]):
            return "shape"
    elif kind in guard.BLOCKED_TYPES or kind in guard.NEVER_CREATE_TYPES:
        return "type"                                     # an id that ends like a script, a shortcut ...
    return ""


def exe_name(app_id: Any) -> str:
    """The exe of a path-shaped id ("Code.exe"), "" for an AUMID."""
    if not isinstance(app_id, str) or "\\" not in app_id or guard.suffix(app_id) != "exe":
        return ""
    return app_id.rsplit("\\", 1)[-1]


def never(name: Any, app_id: Any) -> str:
    """The never-open group (guard.never_app) of an app by its name, its exe or its id read as words ("" when it may
    be opened)."""
    exe = exe_name(app_id)
    return guard.never_app(name, exe) or guard.never_app(app_id if isinstance(app_id, str) else "", exe)


@dataclass(frozen=True)
class AppList:
    """The Start menu's apps Jarvis may open (sorted by name) and how many it left out (never-open, odd ids, twice)."""

    apps: tuple[AppItem, ...] = field(default=(), repr=False)
    left_out: int = 0

    def __repr__(self) -> str:
        return f"AppList({len(self.apps)} app(s), {self.left_out} left out)"


def load(backend: DesktopBackend, *, limit: int = MAX_LISTED) -> AppList:
    """The Start menu through ``backend``, minus the never-open apps and the odd ids (see the module docstring)."""
    entries = backend.start_menu_apps(limit=limit)
    kept: dict[str, AppItem] = {}
    left_out = 0
    for entry in entries:
        app_id = getattr(entry, "app_id", None) if isinstance(entry, AppEntry) else None
        name = getattr(entry, "name", None) if isinstance(entry, AppEntry) else None
        if not isinstance(name, str) or not name.strip() or app_id_problem(app_id) or never(name, app_id):
            left_out += 1
            continue
        if any(unicodedata.category(char) == "Cc" for char in name):
            left_out += 1
            continue
        key = app_id.casefold()
        if key in kept:
            left_out += 1
            continue
        kept[key] = AppItem(app_id, " ".join(name.split()), exe_name(app_id))
    apps = tuple(sorted(kept.values(), key=lambda app: (app.name.casefold(), app.app_id)))
    logger.info("Desktop: %d Start-menu app(s) Jarvis may open, %d left out", len(apps), left_out)
    return AppList(apps, left_out)


def _words(text: Any) -> list[str]:
    return [word for word in guard.words(text, camel=False) if word not in _FILLERS]


def match(words: Any, apps: Iterable[AppItem], *, cap: int = MAX_MATCHED) -> tuple[AppItem, ...]:
    """The apps whose name the owner's ``words`` name (a word of the name in his words - "word" for "Microsoft
    Word"), the most words first, at most ``cap``; none when no word matches."""
    wanted = set(_words(words))
    if not wanted:
        return ()
    scored: list[tuple[int, str, AppItem]] = []
    for app in apps:
        if not isinstance(app, AppItem):
            continue
        name_words = _words(app.name)
        score = sum(1 for word in set(name_words) if word in wanted)
        if score:
            scored.append((score, app.name.casefold(), app))
    scored.sort(key=lambda found: (-found[0], found[1]))
    return tuple(app for _score, _name, app in scored[:max(0, cap)])


def find(apps: Sequence[AppItem], app_id: str) -> AppItem | None:
    """The app with this id (exactly) in ``apps``, or None."""
    return next((app for app in apps if isinstance(app, AppItem) and app.app_id == app_id), None)
